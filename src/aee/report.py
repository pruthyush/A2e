"""Assurance audit report generator interface for Assurance Expiry Engine (AEE).

Generates standardized Markdown reports and JSON findings reflecting temporal
assurance state changes, dependency chains, and append-only audit histories.
"""

from __future__ import annotations

import dataclasses
import json
from datetime import datetime, timezone
from pathlib import Path

from aee.engine import Invalidation
from aee.models import AssuranceModel, ReviewRecord

LIMITATIONS_STATEMENT: str = (
    "This report records that assurance is no longer supported; it does not "
    "determine safety, compliance, or equivalence to patching. Risk conclusions "
    "require qualified human review."
)


def _is_expired(dt: datetime | None, now: datetime) -> bool:
    """Check if a datetime is at or before the evaluation reference time."""
    if dt is None:
        return False
    if dt.tzinfo is not None and now.tzinfo is None:
        now_aware = now.replace(tzinfo=timezone.utc)
        return dt <= now_aware
    if dt.tzinfo is None and now.tzinfo is not None:
        dt_aware = dt.replace(tzinfo=now.tzinfo)
        return dt_aware <= now
    return dt <= now


def write_findings_json(
    invalidations: list[Invalidation],
    output_path: Path | str,
) -> None:
    """Emit JSON findings file with schema version 1.0.

    Args:
        invalidations: List of Invalidation events.
        output_path: Destination file path for JSON output.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "schema_version": "1.0",
        "invalidations": [dataclasses.asdict(inv) for inv in invalidations],
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def write_audit_report(
    model: AssuranceModel,
    history: list[ReviewRecord],
    invalidations: list[Invalidation],
    now: datetime,
    command: str,
    input_hashes: dict[str, str],
    output_path: Path | str,
) -> None:
    """Generate Markdown assurance audit report in the strict six-section format.

    Sections in exact order:
      (a) Summary — facility, standard, counts by claim status, active vs
          expired controls, stale vs current evidence.
      (b) Invalidated claims table — Claim ID | Framework | Requirement |
          Previous status | Triggering control/evidence | Reason | Required
          action. Reasons verbatim from engine.
      (c) Dependency rationale — bullet per claim showing the chain
          (e.g. "EVD-12 stale since 2026-10-01 → CC-04 → AC-07").
      (d) Preserved decision history — ReviewRecord timeline, oldest first.
      (e) Limitations — HARDCODED module-level constant: LIMITATIONS_STATEMENT.
      (f) Reproducibility — SHA-256 of model file (and history file), exact
          command line, ISO-8601 UTC timestamp.

    Args:
        model: Evaluated AssuranceModel instance.
        history: Historical ReviewRecord entries.
        invalidations: Invalidation events generated by the engine.
        now: Evaluation timestamp.
        command: Exact command line invocation.
        input_hashes: Dictionary of SHA-256 hashes (e.g. {"model": ..., "history": ...}).
        output_path: Destination file path.
    """
    lines: list[str] = []

    # Title
    lines.append("# Assurance Audit Report\n")

    # (a) Summary
    lines.append("## Summary\n")
    lines.append(f"- **Facility:** {model.facility}")
    lines.append(f"- **Standard:** {model.standard}")

    count_assured = sum(1 for c in model.claims if c.status == 'assured')
    count_under_review = sum(1 for c in model.claims if c.status == "under_review")
    count_invalidated = sum(1 for c in model.claims if c.status == "invalidated")

    lines.append("- **Claims Status:**")
    lines.append(f"  - Assured: {count_assured}")
    lines.append(f"  - Under Review: {count_under_review}")
    lines.append(f"  - Invalidated: {count_invalidated}")

    expired_controls = sum(
        1
        for c in model.controls
        if c.status == "expired" or _is_expired(c.expires_at, now)
    )
    active_controls = len(model.controls) - expired_controls

    stale_evidence = sum(
        1
        for e in model.evidence
        if e.status == "stale" or _is_expired(e.valid_until, now)
    )
    current_evidence = len(model.evidence) - stale_evidence

    lines.append(f"- **Controls:** {active_controls} active, {expired_controls} expired")
    lines.append(f"- **Evidence:** {current_evidence} current, {stale_evidence} stale\n")

    # (b) Invalidated claims table
    lines.append("## Invalidated Claims Table\n")
    lines.append(
        "| Claim ID | Framework | Requirement | Previous status | "
        "Triggering control/evidence | Reason | Required action |"
    )
    lines.append("|---|---|---|---|---|---|---|")

    if not invalidations:
        lines.append("| - | - | - | - | - | *(No claims currently invalidated)* | - |")
    else:
        claim_map = {c.claim_id: c for c in model.claims}
        for inv in sorted(invalidations, key=lambda x: x.claim_id):
            claim = claim_map.get(inv.claim_id)
            framework = claim.framework if claim else "IEC_62443"
            req = claim.requirement_ref if claim else "N/A"
            action = "Human reassessment required"
            lines.append(
                f"| {inv.claim_id} | {framework} | {req} | {inv.previous_status} | "
                f"{inv.triggering_entity_id} | {inv.reason} | {action} |"
            )
    lines.append("")

    # (c) Dependency rationale
    lines.append("## Dependency Rationale\n")
    if not invalidations:
        lines.append("- None")
    else:
        ev_map = {e.evidence_id: e for e in model.evidence}
        ctrl_map = {c.control_id: c for c in model.controls}
        for inv in sorted(invalidations, key=lambda x: x.claim_id):
            if inv.triggering_entity_type == "evidence":
                ev = ev_map.get(inv.triggering_entity_id)
                if ev and ev.valid_until:
                    date_str = ev.valid_until.strftime("%Y-%m-%d")
                else:
                    date_str = "stale"
                ctrl_id = (
                    ev.control_id
                    if ev
                    else (
                        inv.dependent_controls[0]
                        if inv.dependent_controls
                        else "N/A"
                    )
                )
                chain = (
                    f"{inv.triggering_entity_id} stale since {date_str} → "
                    f"{ctrl_id} → {inv.claim_id}"
                )
            else:
                ctrl = ctrl_map.get(inv.triggering_entity_id)
                if ctrl and ctrl.status == "ineffective":
                    chain = f"{inv.triggering_entity_id} marked ineffective → {inv.claim_id}"
                elif ctrl and ctrl.expires_at:
                    date_str = ctrl.expires_at.strftime("%Y-%m-%d")
                    chain = f"{inv.triggering_entity_id} expired on {date_str} → {inv.claim_id}"
                else:
                    chain = f"{inv.triggering_entity_id} expired → {inv.claim_id}"
            lines.append(f"- {chain}")
    lines.append("")

    # (d) Preserved decision history
    lines.append("## Preserved Decision History\n")
    if not history:
        lines.append("*No review records recorded.*")
    else:
        sorted_history = sorted(history, key=lambda r: r.timestamp)
        for rec in sorted_history:
            rec_utc = (
                rec.timestamp.astimezone(timezone.utc)
                if rec.timestamp.tzinfo
                else rec.timestamp.replace(tzinfo=timezone.utc)
            )
            ts_str = rec_utc.strftime("%Y-%m-%dT%H:%M:%SZ")
            notes_str = f" (Notes: {rec.notes})" if rec.notes else ""
            lines.append(
                f"- **{ts_str}** [{rec.record_id}] {rec.actor} recorded '{rec.action}' "
                f"on claim {rec.claim_id} ({rec.previous_status} → {rec.new_status}) — "
                f"Reason: {rec.reason}{notes_str}"
            )
    lines.append("")

    # (e) Limitations
    lines.append("## Limitations\n")
    lines.append(f"{LIMITATIONS_STATEMENT}\n")

    # (f) Reproducibility
    lines.append("## Reproducibility\n")
    model_sha = input_hashes.get("model", "N/A")
    history_sha = input_hashes.get("history", "N/A")
    now_utc = (
        now.astimezone(timezone.utc)
        if now.tzinfo
        else now.replace(tzinfo=timezone.utc)
    )
    now_iso = now_utc.strftime("%Y-%m-%dT%H:%M:%SZ")
    lines.append(f"- **Model SHA-256:** {model_sha}")
    lines.append(f"- **History SHA-256:** {history_sha}")
    lines.append(f"- **Command Line:** {command}")
    lines.append(f"- **Timestamp (UTC):** {now_iso}\n")

    report_content = "\n".join(lines)
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(report_content, encoding="utf-8")


def generate_report(
    model: AssuranceModel,
    history: list[ReviewRecord],
    now: datetime,
    output_path: Path | str,
) -> None:
    """Generate assurance audit report (convenience wrapper).

    Args:
        model: Evaluated AssuranceModel instance.
        history: Review history records.
        now: Report timestamp.
        output_path: Destination path for report.
    """
    write_audit_report(
        model=model,
        history=history,
        invalidations=[],
        now=now,
        command="aee report",
        input_hashes={},
        output_path=output_path,
    )
